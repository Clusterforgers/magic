//! TypeScript bindings for the wire types, generated with ts-rs (one `.ts` file per type plus `index.ts`).
//!
//! ts-rs over specta: the derive is a plain attribute on the existing serde types and honours their
//! serde attributes, so the engine needs no extra codegen crate or registry.

use std::fs;
use std::path::Path;

use thiserror::Error;
use ts_rs::{Config, ExportError, TS};

use crate::message::{ClientMessage, PROTOCOL_VERSION, ServerMessage};
use crate::rest::{
    AuthErrorCode, CardDetail, CardSearchPage, CheckRequest, ChooseDeck, Credentials,
    DeckBlockedBody, DeckBody, DeckChoiceErrorCode, DeckErrorCode, DeckList, DeckView, GameInfo,
    ImportRequest, ImportResult, JoinCodeRequest, JoinRequest, Joined, LobbyErrorCode, LobbyList,
    MyGames, UserView, VisibilityBody,
};

/// Where the committed bindings live, relative to the workspace root.
pub const GENERATED_DIR: &str = "web/src/protocol/generated";

/// Why bindings could not be generated.
#[derive(Debug, Error)]
pub enum BindingsError {
    /// ts-rs could not render a type.
    #[error("ts-rs export failed: {0}")]
    Export(#[from] ExportError),
    /// A file or directory could not be read or written.
    #[error("bindings io failed: {0}")]
    Io(#[from] std::io::Error),
}

/// Writes every binding into `dir`, first removing the `.ts` files already there.
///
/// Ids are exported as `number`: the JSON carries them as numbers and they never exceed 2^53.
pub fn export_to(dir: &Path) -> Result<(), BindingsError> {
    fs::create_dir_all(dir)?;
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.extension().is_some_and(|ext| ext == "ts") {
            fs::remove_file(path)?;
        }
    }
    let config = Config::new().with_large_int("number").with_out_dir(dir);
    ClientMessage::export_all(&config)?;
    ServerMessage::export_all(&config)?;
    Credentials::export_all(&config)?;
    UserView::export_all(&config)?;
    AuthErrorCode::export_all(&config)?;
    MyGames::export_all(&config)?;
    CardSearchPage::export_all(&config)?;
    CardDetail::export_all(&config)?;
    DeckBody::export_all(&config)?;
    DeckView::export_all(&config)?;
    DeckList::export_all(&config)?;
    CheckRequest::export_all(&config)?;
    ImportRequest::export_all(&config)?;
    ImportResult::export_all(&config)?;
    DeckErrorCode::export_all(&config)?;
    LobbyList::export_all(&config)?;
    GameInfo::export_all(&config)?;
    JoinRequest::export_all(&config)?;
    JoinCodeRequest::export_all(&config)?;
    Joined::export_all(&config)?;
    VisibilityBody::export_all(&config)?;
    LobbyErrorCode::export_all(&config)?;
    ChooseDeck::export_all(&config)?;
    DeckChoiceErrorCode::export_all(&config)?;
    DeckBlockedBody::export_all(&config)?;
    fs::write(dir.join("index.ts"), index(dir)?)?;
    Ok(())
}

/// The barrel file: the protocol version and a re-export of every generated type.
fn index(dir: &Path) -> Result<String, BindingsError> {
    let mut names = Vec::new();
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let is_ts = path.extension().is_some_and(|ext| ext == "ts");
        let stem = path.file_stem().and_then(|s| s.to_str());
        if let Some(stem) = stem.filter(|stem| is_ts && *stem != "index") {
            names.push(stem.to_owned());
        }
    }
    names.sort();
    let mut lines = vec![
        "// Generated by mtg-protocol (MTG_UPDATE_BINDINGS=1 cargo test -p mtg-protocol --test bindings). Do not edit.".to_owned(),
        format!("export const PROTOCOL_VERSION = {PROTOCOL_VERSION};"),
    ];
    lines.extend(
        names
            .iter()
            .map(|name| format!("export type {{ {name} }} from \"./{name}\";")),
    );
    Ok(lines.join("\n") + "\n")
}
