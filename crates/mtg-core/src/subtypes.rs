/// Whether `name` is a subtype some card has.
pub fn is_known_subtype(name: &str) -> bool {
    KNOWN_SUBTYPES.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    //! Goal: the subtype list is sorted for lookup and tells subtypes from the words a valid-string uses.
    use super::*;

    #[test]
    fn the_list_is_sorted_and_unique() {
        assert!(KNOWN_SUBTYPES.windows(2).all(|pair| pair[0] < pair[1]));
    }

    #[test]
    fn subtypes_are_known_and_valid_string_words_are_not() {
        for known in [
            "Elf",
            "Forest",
            "Aura",
            "Equipment",
            "Urza's",
            "Power-Plant",
        ] {
            assert!(is_known_subtype(known), "{known}");
        }
        for word in ["You", "Opponent", "Spell", "Basic", "Creature", ""] {
            assert!(!is_known_subtype(word), "{word}");
        }
    }
}
