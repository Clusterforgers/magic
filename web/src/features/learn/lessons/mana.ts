import { count, has } from '../facts'
import type { Lesson } from '../step'

/** Lesson 2: costs, casting, paying by tapping and by Pay for me, creatures and a mana ability. */
export const MANA: Lesson = {
  id: 'mana',
  title: 'Mana and spells',
  text: 'Reading a cost, casting a creature, paying with your lands, summoning sickness and mana abilities.',
  minutes: 3,
  steps: [
    {
      id: 'land',
      kind: 'do',
      title: 'Your land for the turn',
      text: 'Start with your land for the turn: choose the Forest.',
      presses: ['hand:Forest'],
      allow: { kind: 'land', name: 'Forest' },
      done: (facts) => count(facts.lands, 'Forest') >= 3,
    },
    {
      id: 'cost',
      kind: 'read',
      title: 'A cost',
      text: "A card's cost is at its top. {1}{G} is one mana of any color and one green. Each Forest makes {G}.",
      lit: ['hand:Grizzly Bears'],
    },
    {
      id: 'cast',
      kind: 'do',
      title: 'Cast a creature',
      text: 'Choose Grizzly Bears to cast it.',
      presses: ['hand:Grizzly Bears'],
      allow: { kind: 'cast', name: 'Grizzly Bears' },
      done: (facts) => facts.decision === 'PayMana' || has(facts.creatures, 'Grizzly Bears'),
    },
    {
      id: 'tap',
      kind: 'do',
      title: 'Pay by tapping',
      text: 'Pay by tapping lands: press {@pay.tap} twice, then {@pay.confirm}.',
      presses: ['pay.tap', 'pay.tap', 'pay.confirm'],
      allow: { kind: 'pay', how: 'tap' },
      done: (facts) => has(facts.creatures, 'Grizzly Bears'),
    },
    {
      id: 'creature',
      kind: 'read',
      title: 'A creature',
      text: 'Grizzly Bears is a 2/2: 2 power, 2 toughness. It is marked Sick: a creature cannot attack the turn it arrives.',
      lit: ['board:Grizzly Bears'],
    },
    {
      id: 'cast-2',
      kind: 'do',
      title: 'One more',
      text: 'One Forest is still untapped. Choose Llanowar Elves.',
      presses: ['hand:Llanowar Elves'],
      allow: { kind: 'cast', name: 'Llanowar Elves' },
      done: (facts) => facts.decision === 'PayMana' || has(facts.creatures, 'Llanowar Elves'),
    },
    {
      id: 'auto',
      kind: 'do',
      title: 'Let the game pay',
      text: 'This time let the game choose: press {@pay.auto}, then {@pay.confirm}.',
      presses: ['pay.auto', 'pay.confirm'],
      allow: { kind: 'pay', how: 'auto' },
      done: (facts) => has(facts.creatures, 'Llanowar Elves'),
    },
    {
      id: 'pass',
      kind: 'do',
      title: 'End your turn',
      text: 'All your lands are tapped. Press {@pass.primary}.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.turn >= 4,
    },
    {
      id: 'bot',
      kind: 'watch',
      title: "The bot's turn",
      text: 'The bot plays a land and casts a creature of its own.',
      lit: ['opp.board'],
      done: (facts) => facts.turn >= 5 && facts.mine && facts.decision !== null,
    },
    {
      id: 'untap',
      kind: 'read',
      title: 'Untap',
      text: 'A new turn: your lands untap and you draw a card.',
      lit: ['own.board'],
    },
    {
      id: 'ability',
      kind: 'read',
      title: 'A mana ability',
      text: 'Llanowar Elves has an ability, {T}: Add {G}. It taps for mana like a land, from now on.',
      lit: ['board:Llanowar Elves'],
    },
  ],
}
