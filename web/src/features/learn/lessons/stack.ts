import { has } from '../facts'
import type { Lesson } from '../step'

/** Lesson 4: the stack, priority, a trigger, holding mana open and an instant in response. */
export const STACK: Lesson = {
  id: 'stack',
  title: 'The stack',
  text: 'Spells and abilities wait on the stack; priority, a trigger, and an instant cast in response.',
  minutes: 3,
  steps: [
    {
      id: 'cast',
      kind: 'do',
      title: 'Cast a creature',
      text: 'Choose Hero in Training to cast it.',
      presses: ['hand:Hero in Training'],
      allow: { kind: 'cast', name: 'Hero in Training' },
      done: (facts) => facts.decision === 'PayMana' || has(facts.stack, 'Hero in Training'),
    },
    {
      id: 'pay',
      kind: 'do',
      title: 'Pay',
      text: 'Press {@pay.auto}, then {@pay.confirm}. One Forest stays untapped.',
      presses: ['pay.auto', 'pay.confirm'],
      allow: { kind: 'pay', how: 'auto' },
      done: (facts) => has(facts.stack, 'Hero in Training') || has(facts.creatures, 'Hero in Training'),
    },
    {
      id: 'stack',
      kind: 'read',
      title: 'The stack',
      text: 'A spell does not happen at once. It waits on the [[stack]], and each player may respond to it.',
      lit: ['stack'],
    },
    {
      id: 'resolve',
      kind: 'do',
      title: 'Priority',
      text: 'You have [[priority]]: the right to act. Press {@pass.primary} to pass; when both players pass, the spell resolves.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => has(facts.creatures, 'Hero in Training'),
    },
    {
      id: 'trigger',
      kind: 'do',
      title: 'A trigger',
      text: 'Hero in Training entered, so its ability triggered. Abilities wait on the stack too. Press {@pass.primary}.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.stack.length === 0 && has(facts.hand, 'Forest'),
    },
    {
      id: 'open',
      kind: 'do',
      title: 'Hold mana open',
      text: 'Giant Growth is an instant: it can be cast on any turn. Keep the Forest untapped and press {@pass.primary}.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.turn >= 6,
    },
    {
      id: 'attacked',
      kind: 'do',
      title: 'Attacked',
      text: 'The bot attacks with a Zombie. You could respond now, but block first: press {@pass.primary}.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.decision === 'DeclareBlockers',
    },
    {
      id: 'block',
      kind: 'do',
      title: 'Block',
      text: 'Choose Grizzly Bears to block the Zombie, then press {@block.confirm}. As it stands both would die.',
      presses: ['board:Grizzly Bears', 'block.confirm'],
      allow: { kind: 'block', blocker: 'Grizzly Bears', attacker: 'Dregscape Zombie' },
      done: (facts) => facts.blocking > 0,
    },
    {
      id: 'respond',
      kind: 'do',
      title: 'Respond',
      text: 'Before damage you get priority again. Choose Giant Growth.',
      presses: ['hand:Giant Growth'],
      allow: { kind: 'cast', name: 'Giant Growth' },
      done: (facts) => facts.decision === 'ChooseTargets' || !has(facts.hand, 'Giant Growth'),
    },
    {
      id: 'target',
      kind: 'do',
      title: 'Choose a target',
      text: 'Giant Growth needs a target. Choose your Grizzly Bears, then press {@targets.confirm}.',
      presses: ['board:Grizzly Bears', 'targets.confirm'],
      allow: { kind: 'target', name: 'Grizzly Bears' },
      done: (facts) => facts.decision === 'PayMana' || has(facts.stack, 'Giant Growth'),
    },
    {
      id: 'pay-2',
      kind: 'do',
      title: 'Pay',
      text: 'Press {@pay.auto}, then {@pay.confirm}: the Forest you kept pays for it.',
      presses: ['pay.auto', 'pay.confirm'],
      allow: { kind: 'pay', how: 'auto' },
      done: (facts) => has(facts.stack, 'Giant Growth') || has(facts.graveyard, 'Giant Growth'),
    },
    {
      id: 'end',
      kind: 'read',
      title: 'Until end of turn',
      text: 'Giant Growth resolved before damage: the Bears were 5/5, survived and killed the Zombie. At end of turn they became 2/2 again.',
      lit: ['board:Grizzly Bears', 'opp.graveyard'],
    },
  ],
}
