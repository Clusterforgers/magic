import { has } from '../facts'
import type { Lesson } from '../step'

/** Lesson 3: attacking, blocking, creature damage, the graveyard and winning. */
export const COMBAT: Lesson = {
  id: 'combat',
  title: 'Combat',
  text: 'Choosing attackers, unblocked damage, blocking, creatures dying, and winning the game.',
  minutes: 3,
  steps: [
    {
      id: 'intro',
      kind: 'read',
      title: 'Combat',
      text: 'Combat is the middle of your turn: you choose attackers, the opponent chooses blockers, then damage is dealt.',
      lit: ['turn.badge'],
    },
    {
      id: 'go',
      kind: 'do',
      title: 'Go to combat',
      text: 'Press {@pass.primary} to go to combat.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.decision === 'DeclareAttackers',
    },
    {
      id: 'attack',
      kind: 'do',
      title: 'Attack',
      text: 'Choose Grizzly Bears, then press {@attack.confirm}. Serra Angel arrived this turn and stays home.',
      presses: ['board:Grizzly Bears', 'attack.confirm'],
      allow: { kind: 'attack', names: ['Grizzly Bears'] },
      done: (facts) => facts.attacking > 0,
    },
    {
      id: 'window',
      kind: 'do',
      title: 'Before blocks',
      text: 'An attacker taps. Both players may act before blocks; you have nothing, so press {@pass.primary}.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.step === 'Main2' || facts.turn > 5,
    },
    {
      id: 'hit',
      kind: 'read',
      title: 'A hit',
      text: 'The bot did not block, so Grizzly Bears dealt its 2 damage to the bot.',
      lit: ['opp.life'],
    },
    {
      id: 'pass',
      kind: 'do',
      title: 'End your turn',
      text: 'Press {@pass.primary} to end your turn.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.turn >= 6,
    },
    {
      id: 'block',
      kind: 'do',
      title: 'Block',
      text: 'Two Zombies attack you. A sick creature can still block: choose Serra Angel, then a Zombie, then press {@block.confirm}.',
      presses: ['board:Serra Angel', 'opp:Dregscape Zombie', 'block.confirm'],
      allow: { kind: 'block', blocker: 'Serra Angel', attacker: 'Dregscape Zombie' },
      hint: 'Not yet: block with Serra Angel first.',
      done: (facts) => facts.blocking > 0 || has(facts.theirGraveyard, 'Dregscape Zombie'),
    },
    {
      id: 'damage',
      kind: 'read',
      title: 'Damage',
      text: 'Serra Angel dealt 4 damage to a 2/1 Zombie, so it died and went to the graveyard. The other Zombie hit you for 2.',
      lit: ['opp.graveyard', 'own.life'],
    },
    {
      id: 'go-2',
      kind: 'do',
      title: 'Your turn again',
      text: 'The Zombie that attacked is still tapped, and a tapped creature cannot block. Press {@pass.primary}.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.turn >= 7 && facts.decision === 'DeclareAttackers',
    },
    {
      id: 'all',
      kind: 'do',
      title: 'Attack with all',
      text: 'Press {@attack.all} to attack with everything, then {@attack.confirm}.',
      presses: ['attack.all', 'attack.confirm'],
      allow: { kind: 'attack', names: ['Grizzly Bears', 'Serra Angel'] },
      done: (facts) => facts.attacking >= 2,
    },
    {
      id: 'win',
      kind: 'do',
      title: 'The last hit',
      text: '6 damage against 6 life. Press {@pass.primary}.',
      presses: ['pass.primary'],
      allow: { kind: 'pass' },
      done: (facts) => facts.won,
    },
  ],
}
